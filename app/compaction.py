"""上下文压缩：预算不足时把将被丢弃的早期轮次摘要保留，而不是直接丢弃。

原则：
- 只压缩「本来会被丢掉」的部分，不改变保留区间的语义；
- **滚动合并**：新丢弃的轮次与已有摘要合并，而不是每次对全量重算——
  否则摘要容量被新内容占满，最早的暗号/约束会被挤掉；
- 摘要由前台常驻模型生成（不触发槽位切换），长度受 `max_summary_chars` 限制；
- 摘要失败时退回原行为（丢弃 + `history_truncated` 标记），绝不影响主链路。
"""

# 摘要器人格：只做压缩，不做回答
SUMMARIZE_SYSTEM = (
    "你是对话摘要器。把给定的早期对话压缩成一段中文摘要，必须保留："
    "用户的目标与约束、已确认的事实与数字、专有名词与暗号、未完成的待办。"
    "暗号、编号、版本号必须逐字复制，禁止翻译、缩写、展开或改写。"
    "不要寒暄，不要评价，不要编造，不要输出与摘要无关的内容。"
)

# 摘要插入 system 时的前缀；带「已压缩」字样，便于模型区分摘要与近期原文
SUMMARY_PREFIX = "\n\n【更早对话摘要（已压缩，非原文）】"


def _format(dropped):
    lines = []
    for m in dropped:
        tag = "用户" if m["role"] == "user" else "助手"
        lines.append(f"{tag}：{m['content']}")
    return "\n\n".join(lines)


def build_prompt(dropped, max_chars):
    return (
        f"请把下面这段对话压缩成不超过 {max_chars} 字的中文摘要。\n"
        "第一行必须是「【关键标记】」，把所有暗号、编号逐字列出，用逗号分隔；"
        "没有则写「【关键标记】无」。\n"
        "之后再用要点写目标、事实与数字、待办。\n\n"
        f"{_format(dropped)}\n\n只输出摘要正文，不要加额外标题或解释。"
    )


def merge_prompt(existing, dropped, max_chars):
    """把已有摘要与新丢弃的轮次合并，要求保留旧摘要里的事实。"""
    return (
        f"这是同一段对话的滚动摘要。请把「已有摘要」与「新增对话」合并成"
        f"不超过 {max_chars} 字的新摘要。\n"
        "第一行必须是「【关键标记】」，把已有摘要与新增对话里出现的所有暗号、"
        "编号逐字合并列出（逗号分隔），一个都不能丢；没有则写「【关键标记】无」。\n"
        "硬性要求：已有摘要中的暗号、标记、数字、专有名词必须原样保留"
        "（逐字复制，禁止翻译、缩写、展开或改写），不得因为新增内容而丢弃；"
        "只压缩表述，不丢失事实。\n\n"
        f"【已有摘要】\n{existing}\n\n"
        f"【新增对话】\n{_format(dropped)}\n\n"
        "只输出合并后的摘要正文。"
    )


def note(summary):
    return SUMMARY_PREFIX + summary.strip()
